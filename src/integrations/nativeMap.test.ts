test('pełny koszyk i osobny podgląd są odtwarzane razem bez ech ani utraty zaznaczeń',()=>{
 const chart=createFullChart(true),free=[...chart.domainByNative].filter(([,s])=>s.available),taken=[...chart.domainByNative].find(([,s])=>!s.available)!;
 let options:RendererOptions={},selected:string[]=[];let callbacks=0;
 const mock={setChart(){},setStatus(){},clearSelection(){selected=[];options.onDeselect?.({id:free[0][0]} as Parameters<NonNullable<RendererOptions['onDeselect']>>[0]);},select(ids:string[]){selected=[...ids];for(const id of ids)options.onSelect?.({id} as Parameters<NonNullable<RendererOptions['onSelect']>>[0]);return [];},setSelectionFocus(){},focusSection(){},overview(){},destroy(){}} as unknown as ISeatmapRenderer;
 const map=mountNativeMap({} as HTMLDivElement,chart,{onSeat(){callbacks++},onSector(){callbacks++},onOverview(){callbacks++}},(_el,opts)=>{options=opts;return mock});
 const chosenIds=free.slice(0,10).map(([,s])=>s.id),ownHeld={...free[10][1],available:false,ownedHold:true} as typeof free[number][1]&{ownedHold:true};
 map.update({sector:'101',row:6,seat:taken[1],chosenIds:[...chosenIds,ownHeld.id,'unknown',taken[1].id,chosenIds[0]],inventory:new Map([[ownHeld.id,ownHeld]])});
 assert.equal(options.maxSelection,22);assert.equal(selected.length,12);assert.ok(selected.includes(taken[0]));
 for(const id of chosenIds)assert.ok(selected.includes(chart.nativeByDomain.get(id)!));
 assert.ok(selected.includes(chart.nativeByDomain.get(ownHeld.id)!));
 assert.equal(callbacks,0);
 selected=[];options.onSeatsRevealed?.();assert.equal(selected.length,12);assert.equal(callbacks,0);
 map.update({sector:'102',row:2,seat:free[12][1],chosenIds});assert.equal(selected.length,11);assert.equal(callbacks,0);
 map.update({sector:null,row:6,seat:null,chosenIds:chosenIds.slice(1)});assert.equal(selected.length,9);assert.equal(callbacks,0);
 map.dispose();
});
test('inventory changes update only changed native statuses, restore canonical status, and do not echo selections',()=>{
 const chart=createFullChart(true),free=[...chart.domainByNative].find(([,s])=>s.available)!,calls:{ids:string[];status:string}[]=[],picks:string[]=[];
 let options:RendererOptions={},selected:string[]=[];
 const mock={setChart(){},setStatus(ids:string[],status:string){calls.push({ids:[...ids],status});for(const id of ids)options.onSelect?.({id} as Parameters<NonNullable<RendererOptions['onSelect']>>[0]);},clearSelection(){selected=[];},select(ids:string[]){selected=[...ids];return [];},setSelectionFocus(){},focusSection(){},overview(){},destroy(){}} as unknown as ISeatmapRenderer;
 const map=mountNativeMap({} as HTMLDivElement,chart,{onSeat:s=>picks.push(s.id),onSector(){},onOverview(){}},(_el,opts)=>{options=opts;return mock;});
 calls.length=0;
 const held={...free[1],available:false,price:91,ownedHold:true} as typeof free[1]&{ownedHold:true};
 const inventory=new Map([[held.id,held]]);
 map.update({sector:'101',row:1,seat:null,chosenIds:[held.id],inventory});
 assert.deepEqual(calls,[{ids:[free[0]],status:'booked'}]);
 assert.deepEqual(selected,[free[0]]);
 assert.equal(options.seatPriceLabel?.({id:free[0]} as Parameters<NonNullable<RendererOptions['seatPriceLabel']>>[0]),'91 zł · demo');
 assert.equal(picks.length,0,'status changes are guarded against selection echoes');
 options.onSelect?.({id:free[0]} as Parameters<NonNullable<RendererOptions['onSelect']>>[0]);
 assert.equal(picks.length,1);assert.equal(picks[0],held.id);
 map.update({sector:'101',row:1,seat:null,chosenIds:[held.id],inventory:new Map(inventory)});
 assert.equal(calls.length,1,'an identical snapshot issues no renderer status update');
 map.update({sector:'101',row:1,seat:null,chosenIds:[],inventory:new Map()});
 assert.deepEqual(calls[1],{ids:[free[0]],status:'free'});
 map.dispose();
});
